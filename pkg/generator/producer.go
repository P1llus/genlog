package generator

import (
	"strings"

	"github.com/P1llus/genlog/pkg/template"
)

// Producer is a worker that generates log strings and sends them to a channel.
type Producer struct {
	id        int
	compiler  *template.Compiler
	valuePool *template.ValuePool
	output    chan<- string
	stopChan  <-chan struct{}
	stats     *Stats
	builder   *strings.Builder
	maxCount  int64 // Max logs this producer should generate (0 = unlimited)
	generated int64 // Logs generated by this producer
}

// NewProducer creates a new producer worker.
func NewProducer(
	id int,
	compiler *template.Compiler,
	valuePool *template.ValuePool,
	output chan<- string,
	stopChan <-chan struct{},
	stats *Stats,
	maxCount int64,
) *Producer {
	return &Producer{
		id:        id,
		compiler:  compiler,
		valuePool: valuePool,
		output:    output,
		stopChan:  stopChan,
		stats:     stats,
		builder:   &strings.Builder{},
		maxCount:  maxCount,
		generated: 0,
	}
}

// Run starts the producer worker loop.
func (p *Producer) Run() {
	for {
		// Check if we've reached our per-producer limit
		if p.maxCount > 0 && p.generated >= p.maxCount {
			return
		}

		select {
		case <-p.stopChan:
			return
		default:
			// Select a template based on weights
			tmpl := p.compiler.SelectTemplate(p.valuePool.RNG())

			// Execute template to generate log line
			tmpl.Execute(p.valuePool, p.builder)
			logLine := p.builder.String()

			// Send to output channel (may block if channel is full)
			select {
			case p.output <- logLine:
				// Successfully sent - update stats and counter
				p.generated++
				p.stats.IncrementGenerated()
				p.stats.AddBytes(len(logLine) + 1) // +1 for newline
			case <-p.stopChan:
				// Stop requested while waiting to send
				return
			}
		}
	}
}
